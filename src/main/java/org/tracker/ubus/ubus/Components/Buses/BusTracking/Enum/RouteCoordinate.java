    /**
     * Reverses a list of coordinates to get the opposite direction
     */
    private static List<LatLon> reverse(List<LatLon> coordinates) {
        List<LatLon> reversed = new ArrayList<>(coordinates);
        Collections.reverse(reversed);
        return reversed;
    }

    /**
     * Get all route segments for a specific route in order
     */
    public static List<RouteCoordinate> getRouteSegments(Route route) {
        return Arrays.stream(values())
                .filter(rc -> rc.getRoute() == route)
                .collect(Collectors.toList());
    }

    /**
     * Get coordinates for a specific route segment
     */
    public static List<LatLon> getCoordinates(Route route, Destination from, Destination to) {
        return Arrays.stream(values())
                .filter(rc -> rc.getRoute() == route && rc.getFrom() == from && rc.getTo() == to)
                .findFirst()
                .map(RouteCoordinate::getCoordinates)
                .orElseThrow(() -> new IllegalArgumentException(
                        "No coordinates found for route " + route.getLabel() +
                                " from " + from + " to " + to
                ));
    }

    /**
     * Get all coordinates for a route in the correct order
     */
    public static List<LatLon> getFullRouteCoordinates(Route route) {
        List<LatLon> fullCoordinates = new ArrayList<>();
        List<Destination> destinations = new ArrayList<>(route.getDestinations());

        for (int i = 0; i < destinations.size() - 1; i++) {
            Destination from = destinations.get(i);
            Destination to = destinations.get(i + 1);
            List<LatLon> segment = getCoordinates(route, from, to);

            if (i > 0) {
                fullCoordinates.addAll(segment.subList(1, segment.size()));
            } else {
                fullCoordinates.addAll(segment);
            }
        }

        return fullCoordinates;
    }
